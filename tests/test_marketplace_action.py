"""Tests for the root action.yml and its job-summary renderer.

GitHub Marketplace reads action.yml from the repository root and nowhere
else. A syntax error, a missing required field, or a renamed input is not
caught by anything else in this repo -- it surfaces as a broken published
action in someone else's CI, which is the most expensive place to find out.

The renderer is tested hardest on the paths where no audit ran. Rendering an
empty table for a check that failed to execute would read as a clean bill of
health, which is the exact failure the service's own code is built to avoid.

`import yaml` here is deliberately hard, not `pytest.importorskip`. It used to
be the soft form, and because PyYAML was absent from requirements.txt, CI
silently skipped this entire module -- all 29 guards on the one file that has
already shipped dead-on-arrival once. A green CI run said nothing about
action.yml for as long as that lasted. If the dependency ever goes missing
again the suite must fail, not quietly shrink.
"""

import importlib.util
import json
import subprocess
import sys
from pathlib import Path

import pytest
import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
ACTION_PATH = REPO_ROOT / "action.yml"
RENDERER_PATH = REPO_ROOT / "scripts" / "render_audit_summary.py"


def _load_renderer():
    spec = importlib.util.spec_from_file_location("render_audit_summary", RENDERER_PATH)
    module = importlib.util.module_from_spec(spec)
    sys.modules["render_audit_summary"] = module
    spec.loader.exec_module(module)
    return module


renderer = _load_renderer()


@pytest.fixture(scope="module")
def action():
    return yaml.safe_load(ACTION_PATH.read_text())


# --- Marketplace requirements -------------------------------------------


def test_action_yml_is_at_the_repository_root():
    """Marketplace will not publish an action defined anywhere else, and
    `uses: owner/repo@ref` only resolves a root action.yml."""
    assert ACTION_PATH.is_file()


def test_this_repo_cannot_itself_be_marketplace_published():
    """Documents the constraint rather than asserting a wish.

    Marketplace requires an action repo to contain NO workflow files. This one
    has CI, so the listing must come from the standalone repo generated by
    scripts/publish-action-repo.sh. If this ever starts failing because the
    workflows were deleted, that is a much bigger change than a publish tweak
    and should be a deliberate decision, not a silent one.
    """
    workflows = list((REPO_ROOT / ".github" / "workflows").glob("*.y*ml"))
    assert workflows, (
        "This repo no longer has workflow files. Re-check whether the action "
        "can now be published from here directly instead of via "
        "scripts/publish-action-repo.sh."
    )
    assert (REPO_ROOT / "scripts" / "publish-action-repo.sh").is_file()


def test_the_generated_marketplace_repo_has_no_workflow_files(tmp_path):
    """The one rule that silently disqualifies a Marketplace listing."""
    target = tmp_path / "generated"
    subprocess.run(
        ["bash", str(REPO_ROOT / "scripts" / "publish-action-repo.sh"), str(target)],
        check=True, capture_output=True, text=True,
    )
    files = {p.relative_to(target).as_posix() for p in target.rglob("*") if p.is_file()}
    assert files == {
        "action.yml",
        "README.md",
        "scripts/render_audit_summary.py",
        # The wallet payment path; action.yml calls it by $GITHUB_ACTION_PATH,
        # so a published copy without it fails on the one path that spends money.
        "scripts/x402_pay.py",
    }
    assert not list(target.rglob(".github/workflows/*"))


def test_the_generated_action_is_byte_identical_to_the_source(tmp_path):
    """A generated copy that can drift is the problem this replaced."""
    target = tmp_path / "generated"
    subprocess.run(
        ["bash", str(REPO_ROOT / "scripts" / "publish-action-repo.sh"), str(target)],
        check=True, capture_output=True, text=True,
    )
    assert (target / "action.yml").read_bytes() == ACTION_PATH.read_bytes()
    assert (
        (target / "scripts" / "render_audit_summary.py").read_bytes()
        == RENDERER_PATH.read_bytes()
    )


def test_the_listing_documents_every_input_and_output(tmp_path):
    """The listing is the only thing a browsing developer reads before
    deciding. An input it omits is a feature nobody knows exists; one it
    invents is a broken first impression."""
    target = tmp_path / "generated"
    subprocess.run(
        ["bash", str(REPO_ROOT / "scripts" / "publish-action-repo.sh"), str(target)],
        check=True, capture_output=True, text=True,
    )
    action = yaml.safe_load((target / "action.yml").read_text())
    readme = (target / "README.md").read_text()

    for name in action["inputs"]:
        assert f"`{name}`" in readme, f"input {name} is undocumented"
    for name in action["outputs"]:
        assert f"`{name}`" in readme, f"output {name} is undocumented"


def test_the_listing_quotes_the_real_defaults(tmp_path):
    """A listing promising `retries: 3` while the action does 2 is a support
    ticket. Only the URL default is prose ('hosted'), deliberately."""
    target = tmp_path / "generated"
    subprocess.run(
        ["bash", str(REPO_ROOT / "scripts" / "publish-action-repo.sh"), str(target)],
        check=True, capture_output=True, text=True,
    )
    action = yaml.safe_load((target / "action.yml").read_text())
    readme = (target / "README.md").read_text()

    for name, spec in action["inputs"].items():
        default = spec.get("default", "")
        if not default or default.startswith("http"):
            continue
        row = [ln for ln in readme.splitlines() if ln.startswith(f"| `{name}` |")]
        assert row, f"{name} has no table row"
        assert f"`{default}`" in row[0], (
            f"listing shows a different default for {name} than the action does"
        )


