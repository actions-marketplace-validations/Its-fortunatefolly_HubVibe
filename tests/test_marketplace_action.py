def test_publish_script_refuses_to_overwrite_a_non_empty_directory(tmp_path):
    target = tmp_path / "existing"
    target.mkdir()
    (target / "keepme.txt").write_text("important")
    result = subprocess.run(
        ["bash", str(REPO_ROOT / "scripts" / "publish-action-repo.sh"), str(target)],
        capture_output=True, text=True,
    )
    assert result.returncode != 0
    assert (target / "keepme.txt").read_text() == "important"


def test_there_is_exactly_one_action_definition():
    """A second copy elsewhere in the tree drifts from the published one."""
    found = [
        p
        for p in REPO_ROOT.rglob("action.y*ml")
        if ".git" not in p.parts and "node_modules" not in p.parts
    ]
    assert found == [ACTION_PATH], f"unexpected extra action definitions: {found}"


